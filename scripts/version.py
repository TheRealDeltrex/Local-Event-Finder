#!/usr/bin/env python3
"""Single source of truth for the app version.

The version lives in the top-level ``VERSION`` file. Every deliverable reads it:

* Flask app   — ``eventfinder/__init__.py`` reads ``VERSION`` at import time.
* Android app — ``android/app/build.gradle.kts`` reads ``VERSION`` at build time
  (``versionName``; ``versionCode`` is derived from it).
* Browser app — GitHub Pages can't read files outside ``docs/``, so this script
  stamps the version into ``docs/version.js``.

Usage:
    python scripts/version.py            # print the current version
    python scripts/version.py set 1.2.0  # bump VERSION and stamp docs/version.js
    python scripts/version.py check      # fail if anything is out of sync (CI)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_FILE = ROOT / "VERSION"
WEB_VERSION_FILE = ROOT / "docs" / "version.js"
SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")


def read_version() -> str:
    return VERSION_FILE.read_text(encoding="utf-8").strip()


def web_stamp(version: str) -> str:
    return (
        "// Generated by scripts/version.py from the top-level VERSION file.\n"
        "// Do not edit by hand: run `python scripts/version.py set X.Y.Z`.\n"
        f'window.LEF_VERSION = "{version}";\n'
    )


def write_all(version: str) -> None:
    if not SEMVER.match(version):
        sys.exit(f"'{version}' is not a MAJOR.MINOR.PATCH version")
    VERSION_FILE.write_text(version + "\n", encoding="utf-8")
    WEB_VERSION_FILE.write_text(web_stamp(version), encoding="utf-8")
    print(f"version set to {version}")


def check() -> int:
    version = read_version()
    problems = []
    if not SEMVER.match(version):
        problems.append(f"VERSION '{version}' is not MAJOR.MINOR.PATCH")
    if not WEB_VERSION_FILE.exists() or WEB_VERSION_FILE.read_text(encoding="utf-8") != web_stamp(version):
        problems.append("docs/version.js does not match VERSION (run `python scripts/version.py set " + version + "`)")
    changelog = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    if f"## [{version}]" not in changelog:
        problems.append(f"CHANGELOG.md has no '## [{version}]' entry")
    for p in problems:
        print("version check:", p)
    if not problems:
        print(f"version check: OK ({version})")
    return 1 if problems else 0


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args:
        print(read_version())
    elif args[0] == "set" and len(args) == 2:
        write_all(args[1])
    elif args[0] == "check":
        sys.exit(check())
    else:
        sys.exit(__doc__)
